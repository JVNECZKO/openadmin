// Per-account PHP-FPM pools. Generated vhosts point at
// /run/php/php-fpm-<user>.sock, so the pool must exist before reload.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { all, get, setting } from './db.mjs';
import { systemProvider } from './providers/index.mjs';
import { userHome } from './paths.mjs';
import { getJson } from './json.mjs';
import { limitsFor } from './auth.mjs';

export function phpVersion() {
  const base = '/etc/php';
  if (!fs.existsSync(base)) return null;
  const versions = fs.readdirSync(base).filter((v) => /^\d+\.\d+$/.test(v) && fs.existsSync(path.join(base, v, 'fpm')));
  return versions.sort((a, b) => Number(b.replace('.', '')) - Number(a.replace('.', '')))[0] || null;
}

export function fpmUnit() {
  const v = phpVersion();
  return v ? `php${v}-fpm` : 'php-fpm';
}

export function poolDir() {
  const v = phpVersion();
  return v ? `/etc/php/${v}/fpm/pool.d` : null;
}

export function renderPool(username) {
  const home = userHome(username);
  const f = getJson(`fpm_pool:${username}`, {});
  const get = (k, d) => f[k] !== undefined ? f[k] : d;
  return `; Generated by OpenAdmin for ${username}
[${username}]
user = ${username}
group = ${username}
listen = /run/php/php-fpm-${username}.sock
listen.owner = www-data
listen.group = www-data
listen.mode = 0660
pm = ${get('pm', 'ondemand')}
pm.max_children = ${get('pm.max_children', 10)}
pm.start_servers = ${get('pm.start_servers', 2)}
pm.min_spare_servers = ${get('pm.min_spare_servers', 1)}
pm.max_spare_servers = ${get('pm.max_spare_servers', 3)}
pm.process_idle_timeout = ${get('pm.process_idle_timeout', '10s')}
pm.max_requests = ${get('pm.max_requests', 500)}
request_terminate_timeout = ${get('request_terminate_timeout', '60s')}
rlimit_files = ${get('rlimit_files', 1024)}
chdir = ${home}
php_admin_value[open_basedir] = ${home}:/tmp:/usr/share/php
php_admin_value[upload_tmp_dir] = ${home}/tmp
php_admin_value[sys_temp_dir] = ${home}/tmp
php_admin_value[error_log] = ${home}/logs/php-error.log
php_admin_flag[log_errors] = on
`;
}

export function deployPools() {
  if (systemProvider().id !== 'linux') return { ok: true, simulated: true, output: 'PHP-FPM pools are Linux-only', count: 0 };
  if (process.getuid && process.getuid() !== 0) return { ok: false, output: 'Root privileges are required to write PHP-FPM pools' };
  const dir = poolDir();
  if (!dir) return { ok: false, output: 'PHP-FPM is not installed (/etc/php/*/fpm missing)' };
  const users = all("SELECT username FROM users WHERE level IN ('user','reseller') ORDER BY username");
  const keep = new Set(users.map((u) => u.username));
  for (const f of fs.readdirSync(dir).filter((x) => /^openadmin-.*\.conf$/.test(x))) {
    const owner = f.replace(/^openadmin-/, '').replace(/\.conf$/, '');
    if (!keep.has(owner)) {
      try { fs.rmSync(path.join(dir, f), { force: true }); } catch { /* ignore */ }
    }
  }
  // Retire per-user FPM units for deleted accounts.
  try {
    for (const f of fs.readdirSync('/etc/systemd/system').filter((x) => /^openadmin-php-.*\.service$/.test(x))) {
      const owner = f.replace(/^openadmin-php-/, '').replace(/\.service$/, '');
      if (keep.has(owner)) continue;
      spawnSync('systemctl', ['disable', '--now', f], { encoding: 'utf8', timeout: 15000 });
      try { fs.rmSync(`/etc/systemd/system/${f}`, { force: true }); } catch { /* ignore */ }
      try { fs.rmSync(`/etc/php/${phpVersion()}/fpm/openadmin-${owner}-master.conf`, { force: true }); } catch { /* ignore */ }
      try { fs.rmSync(`/etc/systemd/system/openadmin-user-${owner}.slice`, { force: true }); } catch { /* ignore */ }
      try { fs.rmSync(path.join(path.dirname(dir), 'openadmin-pools', `${owner}.conf`), { force: true }); } catch { /* ignore */ }
    }
  } catch { /* ignore */ }
  let count = 0;
  const errors = [];
  const v = phpVersion();
  const separate = path.join(path.dirname(dir), 'openadmin-pools');
  fs.mkdirSync(separate, { recursive: true, mode: 0o755 });
  const perUser = new Set();
  for (const u of all("SELECT * FROM users WHERE level IN ('user','reseller')")) {
    const home = userHome(u.username);
    if (!fs.existsSync(home)) continue;
    fs.mkdirSync(path.join(home, 'tmp'), { recursive: true, mode: 0o755 });
    fs.mkdirSync(path.join(home, 'logs'), { recursive: true, mode: 0o755 });
    spawnSync('chown', ['-R', `${u.username}:${u.username}`, path.join(home, 'tmp'), path.join(home, 'logs')], { encoding: 'utf8' });
    const lim = limitsFor(u);
    const hard = Number(lim.cpu_percent) > 0 || Number(lim.memory_mb) > 0;
    const globalFile = path.join(dir, `openadmin-${u.username}.conf`);
    const unit = `openadmin-php-${u.username}.service`;
    if (hard) {
      perUser.add(u.username);
      try { fs.rmSync(globalFile, { force: true }); } catch { /* ignore */ }
      const poolFile = path.join(separate, `${u.username}.conf`);
      fs.writeFileSync(poolFile, renderPool(u.username), { mode: 0o644 });
      const master = path.join(path.dirname(dir), `openadmin-${u.username}-master.conf`);
      fs.writeFileSync(master, `[global]
pid = /run/php/openadmin-${u.username}.pid
error_log = /var/log/php-fpm-${u.username}.log
daemonize = no
include = ${poolFile}
`, { mode: 0o644 });
      const slice = `/etc/systemd/system/openadmin-user-${u.username}.slice`;
      fs.mkdirSync(path.dirname(slice), { recursive: true });
      fs.writeFileSync(slice, `[Slice]
${lim.cpu_percent ? `CPUQuota=${Math.max(1, Number(lim.cpu_percent))}%\n` : ''}${lim.memory_mb ? `MemoryMax=${Math.max(64, Number(lim.memory_mb))}M\n` : ''}TasksMax=${Math.max(16, Number(lim.max_processes || 200))}
`, { mode: 0o644 });
      const bin = [`/usr/sbin/php-fpm${v}`, `/usr/sbin/php-fpm`, `/usr/bin/php-fpm${v}`].find((p) => fs.existsSync(p)) || 'php-fpm';
      fs.writeFileSync(`/etc/systemd/system/${unit}`, `[Unit]
Description=OpenAdmin PHP-FPM for ${u.username}
After=network.target

[Service]
Type=simple
Slice=openadmin-user-${u.username}.slice
ExecStart=${bin} --nodaemonize --fpm-config ${master}
Restart=always
RestartSec=2

[Install]
WantedBy=multi-user.target
`, { mode: 0o644 });
      count++;
    } else {
      try {
        spawnSync('systemctl', ['disable', '--now', unit], { encoding: 'utf8', timeout: 15000 });
        fs.rmSync(`/etc/systemd/system/${unit}`, { force: true });
        fs.rmSync(path.join(path.dirname(dir), `openadmin-${u.username}-master.conf`), { force: true });
        fs.rmSync(path.join(separate, `${u.username}.conf`), { force: true });
      } catch { /* ignore */ }
      fs.writeFileSync(globalFile, renderPool(u.username), { mode: 0o644 });
      try { fs.chownSync(globalFile, 0, 0); } catch { /* ignore */ }
      count++;
    }
  }
  spawnSync('systemctl', ['daemon-reload'], { encoding: 'utf8', timeout: 20000 });
  const testCmd = spawnSync('sh', ['-c', `php-fpm${v || ''} -t 2>&1`], { encoding: 'utf8' });
  const served = spawnSync('systemctl', ['reload-or-restart', fpmUnit()], { encoding: 'utf8' });
  for (const name of perUser) {
    const unit = `openadmin-php-${name}.service`;
    const started = spawnSync('systemctl', ['enable', '--now', unit], { encoding: 'utf8', timeout: 30000 });
    if (started.status !== 0) {
      errors.push(`${name}: ${(started.stderr || '').trim().slice(0, 200)}`);
      // Fall back to a global pool so the site never loses PHP.
      fs.writeFileSync(path.join(dir, `openadmin-${name}.conf`), renderPool(name), { mode: 0o644 });
      spawnSync('systemctl', ['disable', '--now', unit], { encoding: 'utf8' });
      spawnSync('systemctl', ['reload-or-restart', fpmUnit()], { encoding: 'utf8' });
    }
  }
  const ok = served.status === 0 && errors.length === 0;
  return {
    ok,
    count,
    output: ok ? `${count} PHP-FPM pool(s) written (${perUser.size} with hard cgroup limits); ${fpmUnit()} reloaded` : `${count} pool(s) written; errors: ${errors.join(' | ') || (served.stderr || '').trim()}`,
    validation: (testCmd.stdout || '').trim().slice(0, 500),
    errors,
  };
}

export function poolStatus(username) {
  const dir = poolDir();
  const file = dir ? path.join(dir, `openadmin-${username}.conf`) : null;
  return {
    exists: !!(file && fs.existsSync(file)),
    file,
    socket: `/run/php/php-fpm-${username}.sock`,
    unit: fpmUnit(),
    version: phpVersion(),
    socketPresent: fs.existsSync(`/run/php/php-fpm-${username}.sock`),
  };
}
