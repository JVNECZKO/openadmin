// Real DKIM key generation and DNS publication.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { config } from './config.mjs';
import { all, get, run, nowIso } from './db.mjs';
import { rebuildZone } from './dns.mjs';
import { systemProvider } from './providers/index.mjs';

export function dkimDir() {
  const dir = path.join(config.dataDir, 'dkim');
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  return dir;
}

export function dkimStatus(domain) {
  const row = get('SELECT * FROM dkim_keys WHERE domain = ?', domain);
  if (!row) return { exists: false, domain };
  return { exists: true, ...row, keyPresent: fs.existsSync(row.key_path) };
}

export function generateDkim(domain, selector = 'default') {
  if (!/^[a-z0-9.-]+$/i.test(domain)) return { ok: false, error: 'Invalid domain' };
  const dir = dkimDir();
  const keyPath = path.join(dir, `${domain}.${selector}.key`);
  const gen = spawnSync('openssl', ['genrsa', '2048'], { encoding: 'buffer', timeout: 30000 });
  if (gen.status !== 0) return { ok: false, error: `openssl genrsa failed: ${(gen.stderr || '').toString().trim()}` };
  fs.writeFileSync(keyPath, gen.stdout, { mode: 0o600 });
  const pub = spawnSync('openssl', ['rsa', '-in', keyPath, '-pubout', '-outform', 'DER'], { encoding: 'buffer', timeout: 20000 });
  if (pub.status !== 0) return { ok: false, error: `openssl pubout failed: ${(pub.stderr || '').toString().trim()}` };
  const publicKey = `v=DKIM1; k=rsa; p=${pub.stdout.toString('base64')}`;
  run(`INSERT INTO dkim_keys(domain, selector, key_path, public_key, created_at) VALUES(?,?,?,?,?)
       ON CONFLICT(domain) DO UPDATE SET selector = excluded.selector, key_path = excluded.key_path,
       public_key = excluded.public_key, created_at = excluded.created_at`,
    domain, selector, keyPath, publicKey, nowIso());
  const d = get('SELECT id FROM domains WHERE name = ?', domain);
  if (d) {
    run("DELETE FROM dns_records WHERE domain_id = ? AND type = 'TXT' AND name = ?", d.id, `${selector}._domainkey`);
    run('INSERT INTO dns_records(domain_id, name, type, value, priority, ttl) VALUES(?,?,?,?,?,?)',
      d.id, `${selector}._domainkey`, 'TXT', publicKey, null, 3600);
    rebuildZone(domain);
  }
  return { ok: true, domain, selector, keyPath, publicKey };
}

/** Deploy private keys and OpenDKIM tables on Linux (root). */
export function deployDkim() {
  const rows = all('SELECT * FROM dkim_keys ORDER BY domain');
  if (systemProvider().id !== 'linux') return { ok: true, simulated: true, output: `DKIM keys are stored in ${dkimDir()} (sandbox provider)` };
  if (process.getuid && process.getuid() !== 0) return { ok: false, output: 'Root privileges are required to deploy DKIM keys' };
  const keyDir = '/etc/opendkim/keys';
  fs.mkdirSync(keyDir, { recursive: true });
  const keyTable = [];
  const signingTable = [];
  const transports = ['# Generated by OpenAdmin — DKIM transports'];
  const routers = ['# Generated by OpenAdmin — DKIM routers'];
  for (const row of rows) {
    const file = path.join(keyDir, `${row.domain}.private`);
    fs.copyFileSync(row.key_path, file);
    fs.chmodSync(file, 0o640);
    try {
      const gid = spawnSync('id', ['-g', 'Debian-exim'], { encoding: 'utf8' });
      if (gid.status === 0) fs.chownSync(file, 0, Number(gid.stdout.trim()));
    } catch { /* exim may not exist */ }
    keyTable.push(`${row.selector}._domainkey.${row.domain} ${row.domain}:${row.selector}:${file}`);
    signingTable.push(`${row.selector}._domainkey.${row.domain} ${row.domain}`);
    const safe = row.domain.replace(/[^a-z0-9]/g, '_');
    transports.push(`openadmin_lmtp_${safe}:
  driver = smtp
  protocol = lmtp
  hosts = 127.0.0.1
  port = 24
  allow_localhost = true
  dkim_domain = ${row.domain}
  dkim_selector = ${row.selector}
  dkim_private_key = ${file}
  dkim_canon = relaxed

openadmin_remote_${safe}:
  driver = smtp
  dkim_domain = ${row.domain}
  dkim_selector = ${row.selector}
  dkim_private_key = ${file}
  dkim_canon = relaxed
`);
    routers.push(`openadmin_local_${safe}:
  driver = accept
  domains = ${row.domain}
  transport = openadmin_lmtp_${safe}
  no_more

openadmin_remote_${safe}:
  driver = dnslookup
  domains = ${row.domain}
  transport = openadmin_remote_${safe}
  no_more
`);
  }
  fs.writeFileSync('/etc/opendkim/KeyTable', keyTable.join('\n') + '\n');
  fs.writeFileSync('/etc/opendkim/SigningTable', signingTable.join('\n') + '\n');
  fs.mkdirSync('/etc/exim4/conf.d/transport', { recursive: true });
  fs.mkdirSync('/etc/exim4/conf.d/router', { recursive: true });
  fs.writeFileSync('/etc/exim4/conf.d/transport/050_openadmin_dkim', transports.join('\n') + '\n', { mode: 0o644 });
  fs.writeFileSync('/etc/exim4/conf.d/router/060_openadmin_dkim', routers.join('\n') + '\n', { mode: 0o644 });
  for (const stale of ['/etc/exim4/conf.d/router/100_openadmin_aliases', '/etc/exim4/conf.d/router/110_openadmin_remote']) {
    try { fs.rmSync(stale, { force: true }); } catch { /* ignore */ }
  }
  spawnSync('update-exim4.conf', [], { encoding: 'utf8', timeout: 30000 });
  const exim = spawnSync('sh', ['-c', 'systemctl stop exim4 2>/dev/null; sleep 1; pkill -x exim4 2>/dev/null; sleep 1; systemctl start exim4'], { encoding: 'utf8', timeout: 30000 });
  const reload = spawnSync('systemctl', ['reload-or-restart', 'opendkim'], { encoding: 'utf8' });
  return {
    ok: exim.status === 0,
    output: `Deployed ${rows.length} DKIM key(s); Exim ${exim.status === 0 ? 'restarted with signing transports' : 'restart failed'}; OpenDKIM ${reload.status === 0 ? 'reloaded' : 'not reloaded'}`,
  };
}
