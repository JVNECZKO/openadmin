async function download(app) {
  const cache = path.join(appsRoot(), 'cache', `${app.id}-${app.version}.tar.gz`);
  if (fs.existsSync(cache) && fs.statSync(cache).size > 100000) return cache;
  const res = await fetch(app.url, { redirect: 'follow' });
  if (!res.ok) throw new Error(`Download failed: HTTP ${res.status} from ${app.url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 100000) throw new Error('Downloaded archive is unexpectedly small');
  fs.writeFileSync(cache, buf);
  return cache;
}

function extract(archive, destination) {
  fs.mkdirSync(destination, { recursive: true });
  const r = spawnSync('tar', ['-xzf', archive, '-C', destination, '--strip-components=1'], { encoding: 'utf8', timeout: 120000 });
  if (r.status !== 0) throw new Error(`Extraction failed: ${(r.stderr || '').trim()}`);
}

export async function install(id) {
  const app = APPS[id];
  if (!app) return { ok: false, error: 'Unknown application' };
  if (!phpExtensions().ok) return { ok: false, error: 'PHP CLI is required to run ' + app.name };
  const dir = appDir(id);
  if (fs.existsSync(path.join(dir, 'index.php'))) return { ok: true, already: true, status: status(id) };
  const archive = await download(app);
  fs.mkdirSync(appsRoot(), { recursive: true });
  const tmp = path.join(appsRoot(), `.install-${id}-${Date.now()}`);
  try {
    extract(archive, tmp);
    fs.rmSync(dir, { recursive: true, force: true });
    fs.renameSync(tmp, dir);
  } catch (e) {
    fs.rmSync(tmp, { recursive: true, force: true });
    return { ok: false, error: e.message };
  }
  if (id === 'phpmyadmin') phpMyAdminConfig(dir);
  else roundcubeConfig(dir);
  fs.writeFileSync(path.join(dir, '.openadmin-version'), app.version);
  const link = path.join(appsRoot(), 'webroot', id);
  try { fs.unlinkSync(link); } catch { /* no old link */ }
  fs.symlinkSync(dir, link, 'dir');
  setSetting(`app_version:${id}`, app.version);
  return { ok: true, status: status(id) };
}

export function start(id) {
  const app = APPS[id];
  const st = status(id);
  if (!st.installed) return { ok: false, error: `${app.name} is not installed` };
  if (st.running) return { ok: true, already: true, pid: st.pid };
  if (st.missingExtensions.length) {
    return { ok: false, error: `${app.name} requires the PHP extension(s): ${st.missingExtensions.join(', ')}` };
  }
  const webroot = path.join(appsRoot(), 'webroot');
  const out = fs.openSync(path.join(appsRoot(), `${id}.log`), 'a');
  const child = spawn('php', ['-S', `127.0.0.1:${app.port}`, '-t', webroot], {
    detached: true, stdio: ['ignore', out, out], cwd: webroot,
  });
  child.unref();
  fs.writeFileSync(pidFile(id), String(child.pid));
  setSetting(`app_pid:${id}`, String(child.pid));
  const started = Date.now();
  while (Date.now() - started < 4000) {
    if (portOpen(app.port)) return { ok: true, pid: child.pid };
    spawnSync('sleep', ['0.15']);
  }
  return { ok: false, error: `${app.name} did not start; see ${path.join(appsRoot(), `${id}.log`)}` };
}

export function stop(id) {
  const pid = readPid(id);
  if (pid && alive(pid)) {
    try { process.kill(pid, 'SIGTERM'); } catch { /* ignore */ }
  }
  try { fs.unlinkSync(pidFile(id)); } catch { /* ignore */ }
  return { ok: true };
}

/* ------------------------------- app cookies ------------------------------ */
// phpMyAdmin's sign-on nonce is carried by a short-lived HttpOnly cookie scoped
// to the application path, never by a URL parameter (SEC-011). `Secure` follows
// the same central policy as the panel session (HTTPS / trusted X-Forwarded-Proto
// / OA_COOKIE_SECURE override), without requiring the auth module to change.
export function requestIsSecure(req) {
  const forced = String(process.env.OA_COOKIE_SECURE ?? '').trim().toLowerCase();
  if (['1', 'true', 'yes', 'on'].includes(forced)) return true;
  if (['0', 'false', 'no', 'off'].includes(forced)) return false;
  if (config.https) return true;
  if (req?.socket?.encrypted) return true;
  const proto = String(req?.headers?.['x-forwarded-proto'] ?? '').split(',')[0].trim().toLowerCase();
  if (proto === 'https') return true;
  return String(process.env.NODE_ENV || '').toLowerCase() === 'production';
}

export function buildCookie(name, value, {
  maxAge = null, secure, httpOnly = true, sameSite = 'Lax', path = '/', req,
} = {}) {
  const parts = [`${name}=${value}`, `Path=${path}`];
  if (httpOnly) parts.push('HttpOnly');
  if (sameSite) parts.push(`SameSite=${sameSite}`);
  if (maxAge !== null && maxAge !== undefined) parts.push(`Max-Age=${Math.max(0, Math.trunc(Number(maxAge) || 0))}`);
  const isSecure = secure === undefined ? requestIsSecure(req) : Boolean(secure);
  if (isSecure) parts.push('Secure');
  return parts.join('; ');
}

export function pmaSignonCookie(token, { secure, req } = {}) {
  return buildCookie('OA_PMA', token, { secure, maxAge: 60, path: '/phpmyadmin', sameSite: 'Strict', req });
}

export function clearPmaSignonCookie({ secure, req } = {}) {
  return buildCookie('OA_PMA', '', { secure, maxAge: 0, path: '/phpmyadmin', req });
}

