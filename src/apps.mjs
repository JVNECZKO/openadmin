export function appsRoot() {
  const dir = path.join(config.dataDir, 'apps');
  fs.mkdirSync(path.join(dir, 'cache'), { recursive: true });
  fs.mkdirSync(path.join(dir, 'webroot'), { recursive: true });
  return dir;
}

export function appDir(id) {
  return path.join(appsRoot(), id);
}

export function phpExtensions() {
  const r = spawnSync('php', ['-m'], { encoding: 'utf8' });
  if (r.status !== 0) return { ok: false, list: [], error: 'PHP CLI not available' };
  return { ok: true, list: r.stdout.toLowerCase().split('\n').map((s) => s.trim()).filter(Boolean), error: '' };
}

function pidFile(id) {
  return path.join(appsRoot(), `${id}.pid`);
}

function readPid(id) {
  try { return Number(fs.readFileSync(pidFile(id), 'utf8').trim()); } catch { return 0; }
}

function alive(pid) {
  if (!pid) return false;
  try { process.kill(pid, 0); return true; } catch { return false; }
}

function portOpen(port) {
  const safePort = Number(port);
  if (!Number.isInteger(safePort) || safePort < 1 || safePort > 65535) return false;
  const r = spawnSync('curl', ['-s', '-o', '/dev/null', '-m', '1', `http://127.0.0.1:${safePort}`], { encoding: 'utf8' });
  return r.status === 0;
}

export function roundcubePreflight() {
  const extensions = phpExtensions();
  const need = ['imap', 'pdo_sqlite'];
  const missing = need.filter((e) => !extensions.list.includes(e));
  const port = Number(setting('imap_port', String(config.imapPort || 1143)));
  const probe = spawnSync(process.execPath, ['-e', `const net=require('net');const s=net.connect(${port},'127.0.0.1');s.on('connect',()=>{s.end();process.exit(0)});s.on('error',()=>process.exit(1));setTimeout(()=>process.exit(1),1500)`], { timeout: 4000 });
  const imapReachable = probe.status === 0;
  const st = status('roundcube');
  return {
    php: extensions.ok,
    missingExtensions: missing,
    imapReachable,
    imapHost: setting('roundcube_imap_host', `127.0.0.1:${port}`),
    installed: st.installed,
    running: st.running,
    config: fs.existsSync(path.join(appDir('roundcube'), 'config', 'config.inc.php')),
    ready: st.installed && missing.length === 0,
  };
}

export function status(id) {
  const app = APPS[id];
  if (!app) return null;
  const dir = appDir(id);
  const installed = fs.existsSync(path.join(dir, id === 'phpmyadmin' ? 'index.php' : 'index.php'));
  const versionFile = path.join(dir, '.openadmin-version');
  const version = fs.existsSync(versionFile) ? fs.readFileSync(versionFile, 'utf8').trim() : '';
  const pid = readPid(id);
  const extensions = phpExtensions();
  const missing = app.requires.filter((ext) => !extensions.list.includes(ext));
  return {
    ...app, installed, version, dir, pid: alive(pid) ? pid : 0,
    running: alive(pid) && portOpen(app.port),
    url: `/${id}/`,
    missingExtensions: missing,
    php: extensions.ok,
  };
}

export function statusAll() {
  return Object.fromEntries(Object.keys(APPS).map((id) => [id, status(id)]));
}

