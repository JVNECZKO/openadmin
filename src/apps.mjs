function roundcubeConfig(dir) {
  const secret = crypto.randomBytes(24).toString('base64').replace(/[^A-Za-z0-9]/g, '').slice(0, 24);
  const db = path.join(appsRoot(), 'roundcube.sqlite');
  const cfg = `<?php
// Generated by OpenAdmin — Roundcube ${APPS.roundcube.version}
$config = [];
$config['db_dsnw'] = 'sqlite:///${db}?mode=0646';
$config['imap_host'] = '${setting('roundcube_imap_host', '127.0.0.1:1143')}';
$config['smtp_host'] = '127.0.0.1:25';
$config['imap_conn_options'] = ['ssl' => ['verify_peer' => false, 'verify_peer_name' => false], 'tls' => []];
$config['smtp_conn_options'] = ['ssl' => ['verify_peer' => false, 'verify_peer_name' => false]];
$config['des_key'] = '${secret}';
$config['product_name'] = 'OpenAdmin Webmail';
$config['skin'] = 'elastic';
$config['plugins'] = ['archive', 'zipdownload'];
$config['enable_installer'] = false;
$config['smtp_user'] = '%u';
$config['smtp_pass'] = '%p';
`;
  fs.writeFileSync(path.join(dir, 'config', 'config.inc.php'), cfg, { mode: 0o600 });
}

async function download(app) {
  const cache = path.join(appsRoot(), 'cache', `${app.id}-${app.version}.tar.gz`);
  if (fs.existsSync(cache) && fs.statSync(cache).size > 100000) return cache;
  const res = await fetch(app.url, { redirect: 'follow' });
  if (!res.ok) throw new Error(`Download failed: HTTP ${res.status} from ${app.url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 100000) throw new Error('Downloaded archive is unexpectedly small');
  fs.writeFileSync(cache, buf);
  return cache;
}

function extract(archive, destination) {
  fs.mkdirSync(destination, { recursive: true });
  const r = spawnSync('tar', ['-xzf', archive, '-C', destination, '--strip-components=1'], { encoding: 'utf8', timeout: 120000 });
  if (r.status !== 0) throw new Error(`Extraction failed: ${(r.stderr || '').trim()}`);
}

export async function install(id) {
  const app = APPS[id];
  if (!app) return { ok: false, error: 'Unknown application' };
  if (!phpExtensions().ok) return { ok: false, error: 'PHP CLI is required to run ' + app.name };
  const dir = appDir(id);
  if (fs.existsSync(path.join(dir, 'index.php'))) return { ok: true, already: true, status: status(id) };
  const archive = await download(app);
  fs.mkdirSync(appsRoot(), { recursive: true });
  const tmp = path.join(appsRoot(), `.install-${id}-${Date.now()}`);
  try {
    extract(archive, tmp);
    fs.rmSync(dir, { recursive: true, force: true });
    fs.renameSync(tmp, dir);
  } catch (e) {
    fs.rmSync(tmp, { recursive: true, force: true });
    return { ok: false, error: e.message };
  }
  if (id === 'phpmyadmin') phpMyAdminConfig(dir);
  else roundcubeConfig(dir);
  fs.writeFileSync(path.join(dir, '.openadmin-version'), app.version);
  const link = path.join(appsRoot(), 'webroot', id);
  try { fs.unlinkSync(link); } catch { /* no old link */ }
  fs.symlinkSync(dir, link, 'dir');
  setSetting(`app_version:${id}`, app.version);
  return { ok: true, status: status(id) };
}

export function start(id) {
  const app = APPS[id];
  const st = status(id);
  if (!st.installed) return { ok: false, error: `${app.name} is not installed` };
  if (st.running) return { ok: true, already: true, pid: st.pid };
  if (st.missingExtensions.length) {
    return { ok: false, error: `${app.name} requires the PHP extension(s): ${st.missingExtensions.join(', ')}` };
  }
  const webroot = path.join(appsRoot(), 'webroot');
  const out = fs.openSync(path.join(appsRoot(), `${id}.log`), 'a');
  const child = spawn('php', ['-S', `127.0.0.1:${app.port}`, '-t', webroot], {
    detached: true, stdio: ['ignore', out, out], cwd: webroot,
  });
  child.unref();
  fs.writeFileSync(pidFile(id), String(child.pid));
  setSetting(`app_pid:${id}`, String(child.pid));
  const started = Date.now();
  while (Date.now() - started < 4000) {
    if (portOpen(app.port)) return { ok: true, pid: child.pid };
    spawnSync('sleep', ['0.15']);
  }
  return { ok: false, error: `${app.name} did not start; see ${path.join(appsRoot(), `${id}.log`)}` };
}

export function stop(id) {
  const pid = readPid(id);
  if (pid && alive(pid)) {
    try { process.kill(pid, 'SIGTERM'); } catch { /* ignore */ }
  }
  try { fs.unlinkSync(pidFile(id)); } catch { /* ignore */ }
  return { ok: true };
}

/** Proxy one HTTP request to the app's loopback listener. */
export function proxy(req, res, id) {
  const app = APPS[id];
  const headers = { ...req.headers, host: `127.0.0.1:${app.port}` };
  const upstream = http.request({ host: '127.0.0.1', port: app.port, method: req.method, path: req.url, headers }, (upr) => {
    const outHeaders = { ...upr.headers };
    delete outHeaders['transfer-encoding'];
    res.writeHead(upr.statusCode || 502, outHeaders);
    upr.pipe(res);
  });
  upstream.on('error', () => {
    if (!res.headersSent) res.writeHead(502, { 'Content-Type': 'text/plain' });
    res.end('Application is not responding');
  });
  req.pipe(upstream);
}

/** Start every installed app that can run (used at panel boot). */
export function ensureStarted() {
  const started = [];
  for (const id of Object.keys(APPS)) {
    const st = status(id);
    if (st.installed && !st.running && !st.missingExtensions.length) {
      const r = start(id);
      if (r.ok) started.push(id);
    }
  }
  return started;
}

/** PHP-FPM pool and nginx snippet for running phpMyAdmin without php -S. */
export function phpFpmConfigs() {
  const dir = path.join(appsRoot(), 'fpm');
  fs.mkdirSync(dir, { recursive: true });
  const pool = `; Generated by OpenAdmin — phpMyAdmin PHP-FPM pool
[openadmin-apps]
user = www-data
group = www-data
listen = /run/php/php-fpm-openadmin.sock
listen.owner = www-data
listen.group = www-data
pm = ondemand
pm.max_children = 5
pm.process_idle_timeout = 10s
php_admin_value[open_basedir] = ${appsRoot()}:/tmp
php_admin_value[upload_max_filesize] = 64M
php_admin_value[post_max_size] = 64M
`;
  const nginx = `# Generated by OpenAdmin — include inside the panel server block
location ^~ /phpmyadmin/ {
    root ${path.join(appsRoot(), 'webroot')};
    index index.php;
    location ~ \\.php$ {
        include fastcgi_params;
        fastcgi_pass unix:/run/php/php-fpm-openadmin.sock;
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
    }
}
`;
  fs.writeFileSync(path.join(dir, 'phpmyadmin-pool.conf'), pool, 'utf8');
  fs.writeFileSync(path.join(dir, 'phpmyadmin-nginx.conf'), nginx, 'utf8');
  return { ok: true, dir, files: ['phpmyadmin-pool.conf', 'phpmyadmin-nginx.conf'] };
}

export function deployPhpFpm() {
  const generated = phpFpmConfigs();
  if (systemProvider().id !== 'linux') return { ok: true, simulated: true, output: `FPM configuration generated in ${generated.dir} (sandbox provider)` };
  if (process.getuid && process.getuid() !== 0) return { ok: false, output: 'Root privileges are required to deploy PHP-FPM configuration' };
  const candidates = ['/etc/php/8.4/fpm/pool.d', '/etc/php/8.3/fpm/pool.d', '/etc/php/8.2/fpm/pool.d', '/etc/php/8.1/fpm/pool.d'];
  const dir = candidates.find((d) => fs.existsSync(d));
  if (!dir) return { ok: false, output: 'No PHP-FPM pool directory found' };
  fs.copyFileSync(path.join(generated.dir, 'phpmyadmin-pool.conf'), path.join(dir, 'openadmin-apps.conf'));
  return { ok: true, output: `Pool installed in ${dir}; add the nginx snippet to the panel vhost and reload PHP-FPM` };
}

