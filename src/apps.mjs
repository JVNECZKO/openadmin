function signonBridgePhp() {
  // The token never appears in a URL: the panel sets a short-lived, HttpOnly
  // cookie scoped to /phpmyadmin. On any failure this helper redirects back to
  // the panel with a machine-readable code, never to a raw signon error page.
  return `<?php
// Generated by OpenAdmin — one-time sign-on for phpMyAdmin (SEC-011).
declare(strict_types=1);

function openadmin_signon_fail(string $code): void {
    header('Cache-Control: no-store');
    header('Referrer-Policy: no-referrer');
    $db = isset($_GET['db']) ? (string) $_GET['db'] : '';
    $target = '/user/databases?pma_error=' . rawurlencode($code);
    if ($db !== '') $target .= '&pma_db=' . rawurlencode($db);
    header('Location: ' . $target, true, 302);
    exit;
}

$token = isset($_COOKIE['OA_PMA']) ? (string) $_COOKIE['OA_PMA'] : '';
if ($token === '') openadmin_signon_fail('missing');
$panelSession = isset($_COOKIE['OA_SESSION']) ? (string) $_COOKIE['OA_SESSION'] : '';
$secretPath = dirname(__DIR__) . '/.pma-signon-secret';
$secret = trim((string) @file_get_contents($secretPath));
if ($secret === '') openadmin_signon_fail('service');

$context = stream_context_create([
    'http' => [
        'method' => 'POST',
        'header' => "Content-Type: application/json\r\nX-OpenAdmin-Secret: " . $secret . "\r\n",
        'content' => json_encode(['token' => $token, 'session' => $panelSession]),
        'timeout' => 5,
        'ignore_errors' => true,
    ],
    'ssl' => ['verify_peer' => false, 'verify_peer_name' => false],
]);
$response = @file_get_contents('${config.https ? 'https' : 'http'}://127.0.0.1:${config.port}/api/phpmyadmin/credentials', false, $context);
$data = $response ? json_decode($response, true) : null;
if (!is_array($data) || empty($data['ok'])) {
    $code = (is_array($data) && isset($data['code'])) ? (string) $data['code'] : 'unavailable';
    openadmin_signon_fail($code);
}

$https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
    || (isset($_SERVER['HTTP_X_FORWARDED_PROTO']) && $_SERVER['HTTP_X_FORWARDED_PROTO'] === 'https');
ini_set('session.use_strict_mode', '1');
ini_set('session.cookie_httponly', '1');
ini_set('session.cookie_samesite', 'Lax');
ini_set('session.cookie_path', '/phpmyadmin');
if ($https) ini_set('session.cookie_secure', '1');
session_name('OpenAdminPMA');
session_start();
$_SESSION['PMA_single_signon_user'] = (string) $data['username'];
$_SESSION['PMA_single_signon_password'] = (string) $data['password'];
$_SESSION['PMA_single_signon_host'] = '127.0.0.1';
session_write_close();
setcookie('OA_PMA', '', [
    'expires' => time() - 3600,
    'path' => '/phpmyadmin',
    'secure' => $https,
    'httponly' => true,
    'samesite' => 'Lax',
]);
$db = isset($data['db']) ? (string) $data['db'] : '';
header('Cache-Control: no-store');
header('Location: ./index.php' . ($db !== '' ? '?db=' . rawurlencode($db) : ''));
exit;
`;
}

/** Configure phpMyAdmin for one-click SSO through the panel. */
export function enablePhpMyAdminSso() {
  const dir = appDir('phpmyadmin');
  if (!fs.existsSync(path.join(dir, 'index.php'))) return { ok: false, error: 'phpMyAdmin is not installed' };
  const secret = panelSecret();
  fs.writeFileSync(pmaSignonSecretPath(), secret, { mode: 0o600 });
  // Remove the legacy secret file that used to be inside the document root.
  try { fs.rmSync(path.join(dir, '.openadmin-secret'), { force: true }); } catch { /* ignore */ }
  fs.writeFileSync(path.join(dir, 'signon.php'), signonBridgePhp(), { mode: 0o600 });
  phpMyAdminConfig(dir, { signon: true });
  return { ok: true, files: ['signon.php', 'config.inc.php'], restart: start('phpmyadmin') };
}

