/* ------------------------------- HTTP proxy ------------------------------- */
// SEC-012: the reverse proxy used to run before panel authentication and leaked
// `Host: 127.0.0.1:8082`, `X-Powered-By` and internal headers. The proxy now
// enforces the panel session itself (defence in depth for the server.mjs order),
// strips hop-by-hop/internal headers in both directions, presents the external
// host/scheme to the application and never forwards the panel session cookie to
// third-party PHP code (except to the regenerated signon bridge).

const HOP_BY_HOP = new Set([
  'connection', 'keep-alive', 'proxy-authenticate', 'proxy-authorization',
  'proxy-connection', 'te', 'trailer', 'transfer-encoding', 'upgrade',
]);
const INTERNAL_REQUEST_HEADERS = new Set([
  'authorization', 'x-openadmin-secret', 'x-openadmin-internal', 'x-real-ip',
  'x-forwarded-for', 'x-forwarded-host', 'x-forwarded-proto', 'x-forwarded-port',
  'x-forwarded-server', 'forwarded', 'x-request-id',
]);
const INTERNAL_RESPONSE_HEADERS = new Set([
  'x-powered-by', 'server', 'via', 'x-aspnet-version', 'x-aspnetmvc-version',
  'x-debug-token', 'x-debug-token-link',
]);

function connectionTokens(headers) {
  const raw = headers?.connection ?? headers?.Connection ?? '';
  return new Set(String(raw).toLowerCase().split(',').map((v) => v.trim()).filter(Boolean));
}

function externalProto(req) {
  const forced = String(process.env.OA_COOKIE_SECURE ?? '').trim().toLowerCase();
  if (['1', 'true', 'yes', 'on'].includes(forced)) return 'https';
  if (config.https || req?.socket?.encrypted) return 'https';
  const proto = String(req?.headers?.['x-forwarded-proto'] ?? '').split(',')[0].trim().toLowerCase();
  return proto === 'https' ? 'https' : 'http';
}

/** Build the header set sent to the loopback application. */
export function proxyRequestHeaders(req, { secure = false, host = '', ip = '', keepPanelSession = false } = {}) {
  const drop = new Set([...HOP_BY_HOP, ...connectionTokens(req?.headers)]);
  const out = {};
  for (const [name, value] of Object.entries(req?.headers || {})) {
    const key = String(name).toLowerCase();
    if (drop.has(key) || INTERNAL_REQUEST_HEADERS.has(key)) continue;
    if (key === 'cookie') {
      out.cookie = filterCookieHeader(value, { keepPanelSession });
      if (!out.cookie) delete out.cookie;
      continue;
    }
    out[key] = value;
  }
  const externalHost = host || String(req?.headers?.host || '');
  if (externalHost) out.host = externalHost;
  out['x-forwarded-host'] = externalHost;
  out['x-forwarded-proto'] = secure ? 'https' : 'http';
  out['x-forwarded-port'] = secure ? '443' : '80';
  if (ip) out['x-forwarded-for'] = ip;
  return out;
}

/** Remove the panel session cookie before handing a request to third-party code. */
export function filterCookieHeader(header, { keepPanelSession = false } = {}) {
  const pairs = String(header || '').split(';').map((p) => p.trim()).filter(Boolean);
  const kept = pairs.filter((pair) => {
    const name = pair.slice(0, pair.indexOf('=') === -1 ? pair.length : pair.indexOf('=')).trim();
    if (name === cookieName() && !keepPanelSession) return false;
    return true;
  });
  return kept.join('; ');
}

/** Strip internal/fingerprinting headers and enforce Secure on app cookies. */
export function proxyResponseHeaders(headers, { secure = false, appId = '' } = {}) {
  const drop = new Set([...HOP_BY_HOP, ...connectionTokens(headers), ...INTERNAL_RESPONSE_HEADERS]);
  const out = {};
  for (const [name, value] of Object.entries(headers || {})) {
    const key = String(name).toLowerCase();
    if (drop.has(key)) continue;
    if (key.startsWith('x-openadmin') || key.startsWith('x-internal')) continue;
    out[key] = value;
  }
  const cookies = out['set-cookie'];
  if (cookies) {
    out['set-cookie'] = (Array.isArray(cookies) ? cookies : [cookies]).map((cookie) => {
      let value = String(cookie);
      if (secure && !/;\s*secure\b/i.test(value)) value += '; Secure';
      if (appId === 'phpmyadmin' && /(?:^|;)\s*path=/i.test(value) && !/;\s*httponly\b/i.test(value)) {
        // phpMyAdmin's own session cookie is never needed by JavaScript.
        value += '; HttpOnly';
      }
      return value;
    });
  }
  out['x-content-type-options'] = 'nosniff';
  out['referrer-policy'] = 'no-referrer';
  return out;
}

/** Resolve the panel session for a proxied request (the proxy runs pre-session). */
export function proxySession(req) {
  const token = parseCookies(req?.headers?.cookie || '')[cookieName()];
  if (!token) return null;
  return getSession(token);
}

function proxyRedirect(res, location) {
  res.writeHead(302, { Location: location, 'Cache-Control': 'no-store' });
  res.end();
}

function isDotFileRequest(rawUrl) {
  const pathname = String(rawUrl || '').split('?')[0];
  return pathname.split('/').some((segment) => (segment.startsWith('.') && segment !== '' && segment !== '.') || segment === '..');
}

/** Proxy one HTTP request to the app's loopback listener. */
export function proxy(req, res, id) {
  const app = APPS[id];
  if (!app) {
    res.writeHead(404, { 'Content-Type': 'text/plain; charset=utf-8' });
    return res.end('Unknown application');
  }
  const found = proxySession(req);
  if (!found) {
    const next = encodeURIComponent(String(req.url || `/${id}/`));
    return proxyRedirect(res, `/login?next=${next}`);
  }
  // The proxy runs before server.mjs resolves the session. Look the preview
  // state up independently so read-only/support sessions cannot use a
  // database-backed application to bypass the write lock.
  const rawSession = parseCookies(req.headers?.cookie || '')[cookieName()];
  const preview = rawSession ? impersonationForSession(rawSession) : null;
  if (found.support || preview?.readOnly) {
    const flash = encodeURIComponent('Podgląd konta jest tylko do odczytu — aplikacja nie może otworzyć sesji z prawem zapisu.');
    const target = id === 'phpmyadmin' ? '/user/databases' : '/user/email';
    const query = id === 'phpmyadmin' ? `pma_error=read_only` : `flash=${flash}&type=error`;
    return proxyRedirect(res, `${target}?${query}`);
  }
  if (isDotFileRequest(req.url)) {
    res.writeHead(404, { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' });
    return res.end('Not found');
  }

  const secure = externalProto(req) === 'https';
  const signonBridge = id === 'phpmyadmin' && String(req.url || '').split('?')[0] === '/phpmyadmin/signon.php';
  const headers = proxyRequestHeaders(req, {
    secure,
    host: String(req.headers?.host || ''),
    ip: String(req.socket?.remoteAddress || '').replace(/^::ffff:/, ''),
    keepPanelSession: signonBridge,
  });
  const upstream = http.request({ host: '127.0.0.1', port: app.port, method: req.method, path: req.url, headers }, (upr) => {
    const outHeaders = proxyResponseHeaders(upr.headers, { secure, appId: id });
    res.writeHead(upr.statusCode || 502, outHeaders);
    upr.pipe(res);
  });
  upstream.setTimeout(30000, () => upstream.destroy(new Error('Application timeout')));
  upstream.on('error', () => {
    if (!res.headersSent) res.writeHead(502, { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' });
    if (!res.writableEnded) res.end('Application is not responding');
  });
  req.pipe(upstream);
}

/** Start every installed app that can run (used at panel boot). */
export function ensureStarted() {
  const started = [];
  for (const id of Object.keys(APPS)) {
    const st = status(id);
    if (st.installed && !st.running && !st.missingExtensions.length) {
      const r = start(id);
      if (r.ok) started.push(id);
    }
  }
  return started;
}

/** PHP-FPM pool and nginx snippet for running phpMyAdmin without php -S. */
export function phpFpmConfigs() {
  const dir = path.join(appsRoot(), 'fpm');
  fs.mkdirSync(dir, { recursive: true });
  const pool = `; Generated by OpenAdmin — phpMyAdmin PHP-FPM pool
[openadmin-apps]
user = www-data
group = www-data
listen = /run/php/php-fpm-openadmin.sock
listen.owner = www-data
listen.group = www-data
pm = ondemand
pm.max_children = 5
pm.process_idle_timeout = 10s
php_admin_value[open_basedir] = ${appsRoot()}:/tmp
php_admin_value[upload_max_filesize] = 64M
php_admin_value[post_max_size] = 64M
`;
  const nginx = `# Generated by OpenAdmin — include inside the panel server block
location = /openadmin-phpmyadmin-auth {
    internal;
    proxy_pass http://127.0.0.1:${config.port}/api/phpmyadmin/session;
    proxy_pass_request_body off;
    proxy_set_header Content-Length "";
    proxy_set_header Cookie $http_cookie;
}
location ^~ /phpmyadmin/ {
    # SEC-012: the FPM path must not bypass the panel session gate.
    auth_request /openadmin-phpmyadmin-auth;
    root ${path.join(appsRoot(), 'webroot')};
    index index.php;
    location ~ \\.php$ {
        include fastcgi_params;
        fastcgi_pass unix:/run/php/php-fpm-openadmin.sock;
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
    }
}
`;
  fs.writeFileSync(path.join(dir, 'phpmyadmin-pool.conf'), pool, 'utf8');
  fs.writeFileSync(path.join(dir, 'phpmyadmin-nginx.conf'), nginx, 'utf8');
  return { ok: true, dir, files: ['phpmyadmin-pool.conf', 'phpmyadmin-nginx.conf'] };
}

export function deployPhpFpm() {
  const generated = phpFpmConfigs();
  if (systemProvider().id !== 'linux') return { ok: true, simulated: true, output: `FPM configuration generated in ${generated.dir} (sandbox provider)` };
  if (process.getuid && process.getuid() !== 0) return { ok: false, output: 'Root privileges are required to deploy PHP-FPM configuration' };
  const candidates = ['/etc/php/8.4/fpm/pool.d', '/etc/php/8.3/fpm/pool.d', '/etc/php/8.2/fpm/pool.d', '/etc/php/8.1/fpm/pool.d'];
  const dir = candidates.find((d) => fs.existsSync(d));
  if (!dir) return { ok: false, output: 'No PHP-FPM pool directory found' };
  fs.copyFileSync(path.join(generated.dir, 'phpmyadmin-pool.conf'), path.join(dir, 'openadmin-apps.conf'));
  return { ok: true, output: `Pool installed in ${dir}; add the nginx snippet to the panel vhost and reload PHP-FPM` };
}

