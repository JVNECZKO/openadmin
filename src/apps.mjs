export function appsRoot() {
  const dir = path.join(config.dataDir, 'apps');
  fs.mkdirSync(path.join(dir, 'cache'), { recursive: true });
  fs.mkdirSync(path.join(dir, 'webroot'), { recursive: true });
  return dir;
}

export function appDir(id) {
  return path.join(appsRoot(), id);
}

export function phpExtensions() {
  const r = spawnSync('php', ['-m'], { encoding: 'utf8' });
  if (r.status !== 0) return { ok: false, list: [], error: 'PHP CLI not available' };
  return { ok: true, list: r.stdout.toLowerCase().split('\n').map((s) => s.trim()).filter(Boolean), error: '' };
}

function pidFile(id) {
  return path.join(appsRoot(), `${id}.pid`);
}

function readPid(id) {
  try { return Number(fs.readFileSync(pidFile(id), 'utf8').trim()); } catch { return 0; }
}

function alive(pid) {
  if (!pid) return false;
  try { process.kill(pid, 0); return true; } catch { return false; }
}

function portOpen(port) {
  const r = spawnSync('sh', ['-c', `curl -s -o /dev/null -m 1 http://127.0.0.1:${port} || exit 1`]);
  return r.status === 0;
}

export function roundcubePreflight() {
  const extensions = phpExtensions();
  const need = ['imap', 'pdo_sqlite'];
  const missing = need.filter((e) => !extensions.list.includes(e));
  const port = Number(setting('imap_port', String(config.imapPort || 1143)));
  const probe = spawnSync(process.execPath, ['-e', `const net=require('net');const s=net.connect(${port},'127.0.0.1');s.on('connect',()=>{s.end();process.exit(0)});s.on('error',()=>process.exit(1));setTimeout(()=>process.exit(1),1500)`], { timeout: 4000 });
  const imapReachable = probe.status === 0;
  const st = status('roundcube');
  return {
    php: extensions.ok,
    missingExtensions: missing,
    imapReachable,
    imapHost: setting('roundcube_imap_host', `127.0.0.1:${port}`),
    installed: st.installed,
    running: st.running,
    config: fs.existsSync(path.join(appDir('roundcube'), 'config', 'config.inc.php')),
    ready: st.installed && missing.length === 0,
  };
}

export function status(id) {
  const app = APPS[id];
  if (!app) return null;
  const dir = appDir(id);
  const installed = fs.existsSync(path.join(dir, id === 'phpmyadmin' ? 'index.php' : 'index.php'));
  const versionFile = path.join(dir, '.openadmin-version');
  const version = fs.existsSync(versionFile) ? fs.readFileSync(versionFile, 'utf8').trim() : '';
  const pid = readPid(id);
  const extensions = phpExtensions();
  const missing = app.requires.filter((ext) => !extensions.list.includes(ext));
  return {
    ...app, installed, version, dir, pid: alive(pid) ? pid : 0,
    running: alive(pid) && portOpen(app.port),
    url: `/${id}/`,
    missingExtensions: missing,
    php: extensions.ok,
  };
}

export function statusAll() {
  return Object.fromEntries(Object.keys(APPS).map((id) => [id, status(id)]));
}

function phpMyAdminConfig(dir, { signon = false } = {}) {
  const secret = crypto.randomBytes(24).toString('base64').replace(/[^A-Za-z0-9]/g, '').slice(0, 32);
  const auth = signon
    ? `$cfg['Servers'][$i]['auth_type'] = 'signon';
$cfg['Servers'][$i]['SignonSession'] = 'OpenAdminPMA';
$cfg['Servers'][$i]['SignonURL'] = 'signon.php';
$cfg['Servers'][$i]['LogoutURL'] = '../user/databases';`
    : "$cfg['Servers'][$i]['auth_type'] = 'cookie';";
  const cfg = `<?php
// Generated by OpenAdmin — phpMyAdmin ${APPS.phpmyadmin.version}
declare(strict_types=1);
$cfg['blowfish_secret'] = '${secret}';
$i = 0;
$i++;
${auth}
$cfg['Servers'][$i]['host'] = '127.0.0.1';
$cfg['Servers'][$i]['port'] = '3306';
$cfg['Servers'][$i]['compress'] = false;
$cfg['Servers'][$i]['AllowNoPassword'] = false;
$cfg['UploadDir'] = '';
$cfg['SaveDir'] = '';
$cfg['TempDir'] = '${path.join(dir, 'tmp')}';
`;
  fs.mkdirSync(path.join(dir, 'tmp'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'config.inc.php'), cfg, { mode: 0o600 });
}

/** Configure phpMyAdmin for one-click SSO through the panel. */
export function enablePhpMyAdminSso() {
  const dir = appDir('phpmyadmin');
  if (!fs.existsSync(path.join(dir, 'index.php'))) return { ok: false, error: 'phpMyAdmin is not installed' };
  const secret = panelSecret();
  fs.writeFileSync(path.join(dir, '.openadmin-secret'), secret, { mode: 0o600 });
  const php = `<?php
// Generated by OpenAdmin — one-time sign-on for phpMyAdmin
$token = $_GET['token'] ?? '';
$secret = trim(@file_get_contents(__DIR__ . '/.openadmin-secret'));
$ctx = stream_context_create(['http' => [
  'method' => 'POST',
  'header' => "Content-Type: application/json\r\nX-OpenAdmin-Secret: " . $secret . "\r\n",
  'content' => json_encode(['token' => $token]),
  'timeout' => 5,
]]);
$resp = @file_get_contents('http://127.0.0.1:${config.port}/api/phpmyadmin/credentials', false, $ctx);
$data = $resp ? json_decode($resp, true) : null;
if (!$data || empty($data['ok'])) { http_response_code(403); echo 'Single sign-on failed or expired.'; exit; }
session_name('OpenAdminPMA');
session_start();
$_SESSION['PMA_single_signon_user'] = $data['username'];
$_SESSION['PMA_single_signon_password'] = $data['password'];
$_SESSION['PMA_single_signon_host'] = '127.0.0.1';
session_write_close();
header('Location: ./index.php');
exit;
`;
  fs.writeFileSync(path.join(dir, 'signon.php'), php, { mode: 0o600 });
  phpMyAdminConfig(dir, { signon: true });
  return { ok: true, files: ['signon.php', 'config.inc.php'], restart: start('phpmyadmin') };
}

export function setRoundcubeImapHost(host) {
  setSetting('roundcube_imap_host', String(host || '127.0.0.1:1143'));
  const dir = appDir('roundcube');
  if (fs.existsSync(path.join(dir, 'index.php'))) roundcubeConfig(dir);
  return { ok: true, host: setting('roundcube_imap_host', '127.0.0.1:1143') };
}

