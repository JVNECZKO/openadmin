const SSHD_DROPIN = '/etc/ssh/sshd_config.d/99-openadmin.conf';
const FIREWALL_FILE = '/etc/openadmin/firewall.nft';
const ROOT_KEYS = '/root/.ssh/authorized_keys';
const PWSQUALITY = '/etc/security/pwquality.conf.d/99-openadmin.conf';
const LIMITS = '/etc/security/limits.d/99-openadmin.conf';
const MODSEC_CONF = '/etc/modsecurity/openadmin.conf';

export function capabilities() {
  const nft = which('nft');
  const sshd = which('sshd') || '/usr/sbin/sshd';
  const apache = which('apache2ctl');
  const modsec = apache ? sh('apache2ctl', ['-M']).stdout.includes('security2_module') : false;
  const exim = which('exim4') || which('exim');
  return {
    provider: config.provider,
    root: config.provider === 'linux' ? isRoot() : true,
    nft: !!nft,
    ssh: fs.existsSync(sshd),
    apache: !!apache,
    modsecurity: modsec,
    exim: !!exim,
    countryLists: !!which('curl'),
  };
}

function blockRows() {
  return all("SELECT * FROM ip_blocks WHERE expires_at IS NULL OR expires_at > ? ORDER BY created_at DESC", nowIso());
}

function eximUid() {
  for (const name of ['Debian-exim', 'exim']) {
    const r = sh('id', ['-u', name]);
    if (r.ok && /^\d+$/.test(r.stdout)) return Number(r.stdout);
  }
  return null;
}

function firewallText({ blocks = blockRows(), countries = [], smtp = false } = {}) {
  const v4 = [];
  const v6 = [];
  for (const b of blocks) (ipFamily(b.cidr) === 6 ? v6 : v4).push(b.cidr);
  for (const c of countries) {
    const dir = path.join(config.dataDir, 'geoip');
    for (const [file, list] of [[`${c}-aggregated.zone`, v4], [`${c}-aggregated.zone.ipv6`, v6]]) {
      const p = path.join(dir, file);
      if (!fs.existsSync(p)) continue;
      for (const line of fs.readFileSync(p, 'utf8').split('\n')) {
        const cidr = line.trim();
        if (cidr && !cidr.startsWith('#') && validCidr(cidr)) list.push(cidr);
      }
    }
  }
  const lines = [
    '# Generated by OpenAdmin — do not edit by hand.',
    'table inet openadmin_filter {',
    '  set blocked4 { type ipv4_addr; flags interval; }',
    '  set blocked6 { type ipv6_addr; flags interval; }',
    '  chain input {',
    '    type filter hook input priority -10; policy accept;',
    '    ip saddr @blocked4 drop',
    '    ip6 saddr @blocked6 drop',
    '  }',
  ];
  if (smtp) {
    const uid = eximUid();
    lines.push('  chain output {');
    lines.push('    type filter hook output priority 0; policy accept;');
    lines.push(`    meta skuid != 0${uid ? ` meta skuid != ${uid}` : ''} tcp dport { 25, 465, 587 } reject with icmp type admin-prohibited`);
    lines.push('  }');
  }
  lines.push('}');
  const withElements = [];
  if (v4.length) withElements.push(`add element inet openadmin_filter blocked4 { ${[...new Set(v4)].join(', ')} }`);
  if (v6.length) withElements.push(`add element inet openadmin_filter blocked6 { ${[...new Set(v6)].join(', ')} }`);
  return `${lines.join('\n')}\n${withElements.join('\n')}${withElements.length ? '\n' : ''}`;
}

export function applyFirewall() {
  if (config.provider !== 'linux') {
    const text = firewallText();
    writeManaged(FIREWALL_FILE, text, { mode: 0o600, backup: false });
    return { ok: true, simulated: true, output: 'Firewall rules written to the sandbox' };
  }
  if (!isRoot()) return { ok: false, error: 'Root privileges are required' };
  if (!which('nft')) return { ok: false, error: 'nftables (nft) is not installed; install nftables first' };
  const countries = all("SELECT country FROM country_blocks WHERE mode = 'block'").map((r) => r.country);
  const text = firewallText({ countries, smtp: setting('smtp_restrictions', '0') === '1' });
  const file = FIREWALL_FILE;
  fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
  backupFile(file);
  fs.writeFileSync(file, text, { mode: 0o600 });
  sh('nft', ['delete', 'table', 'inet', 'openadmin_filter']);
  const applied = sh('nft', ['-f', file]);
  if (!applied.ok) return { ok: false, error: applied.stderr || applied.error || 'nft failed' };
  const unit = '/etc/systemd/system/openadmin-firewall.service';
  if (!fs.existsSync(unit)) {
    fs.writeFileSync(unit, `[Unit]\nDescription=OpenAdmin firewall rules\nAfter=network-pre.target\nBefore=network.target\n\n[Service]\nType=oneshot\nExecStart=${which('nft')} -f ${file}\nRemainAfterExit=yes\n\n[Install]\nWantedBy=multi-user.target\n`, { mode: 0o644 });
    sh('systemctl', ['daemon-reload']);
    sh('systemctl', ['enable', 'openadmin-firewall.service']);
  }
  return { ok: true, output: `Firewall applied (${blockRows().length} IP block(s), ${countries.length} country list(s))`, simulated: false };
}

export function addIpBlock(cidr, { reason = '', expiresAt = null, actor = 'admin' } = {}) {
  const value = String(cidr || '').trim();
  if (!validCidr(value)) return { ok: false, error: 'Invalid IPv4/IPv6 address or CIDR' };
  if (get('SELECT id FROM ip_blocks WHERE cidr = ?', value)) return { ok: false, error: 'This address is already blocked' };
  run('INSERT INTO ip_blocks(cidr, reason, created_by, expires_at, created_at) VALUES(?,?,?,?,?)', value, reason, actor, expiresAt, nowIso());
  const applied = applyFirewall();
  audit(actor, 'admin', 'security.ipblock.add', value, '');
  return applied.ok ? { ok: true, applied } : { ok: false, error: applied.error, stored: true };
}

export function removeIpBlock(id, actor = 'admin') {
  const row = get('SELECT * FROM ip_blocks WHERE id = ?', Number(id));
  if (!row) return { ok: false, error: 'Not found' };
  run('DELETE FROM ip_blocks WHERE id = ?', row.id);
  const applied = applyFirewall();
  audit(actor, 'admin', 'security.ipblock.remove', row.cidr, '');
  return applied.ok ? { ok: true, applied } : { ok: false, error: applied.error };
}

export function getSsh() {
  const managed = readManaged(SSHD_DROPIN) || '';
  const main = (() => { try { return fs.readFileSync('/etc/ssh/sshd_config', 'utf8'); } catch { return ''; } })();
  const pick = (key) => {
    const m = new RegExp(`^\\s*${key}\\s+(\\S+)`, 'im').exec(managed) || new RegExp(`^\\s*${key}\\s+(\\S+)`, 'im').exec(main);
    return m ? m[1] : '';
  };
  return {
    port: Number(pick('Port') || 22),
    password_authentication: (pick('PasswordAuthentication') || 'yes') !== 'no',
    permit_root_login: pick('PermitRootLogin') || 'prohibit-password',
    max_auth_tries: Number(pick('MaxAuthTries') || 6),
    dropin: SSHD_DROPIN,
    managed: !!readManaged(SSHD_DROPIN),
  };
}

export function saveSsh(body, actor = 'admin') {
  const port = Number(body.port || 22);
  if (!Number.isInteger(port) || port < 1 || port > 65535) return { ok: false, error: 'Port must be 1–65535' };
  const permit = ['yes', 'no', 'prohibit-password', 'forced-commands-only'].includes(String(body.permit_root_login)) ? String(body.permit_root_login) : 'prohibit-password';
  const max = Math.min(20, Math.max(1, Number(body.max_auth_tries || 6)));
  const text = `# Managed by OpenAdmin Security Center\nPort ${port}\nPasswordAuthentication ${body.password_authentication ? 'yes' : 'no'}\nPermitRootLogin ${permit}\nMaxAuthTries ${max}\n`;
  const previous = readManaged(SSHD_DROPIN);
  writeManaged(SSHD_DROPIN, text, { mode: 0o600 });
  if (config.provider === 'linux') {
    const check = validateSshd(SSHD_DROPIN);
    if (!check.ok) {
      if (previous !== null) writeManaged(SSHD_DROPIN, previous, { mode: 0o600, backup: false });
      return { ok: false, error: `sshd validation failed: ${check.stderr || check.error}` };
    }
    const reload = serviceReload('ssh');
    if (!reload.ok) {
      if (previous !== null) writeManaged(SSHD_DROPIN, previous, { mode: 0o600, backup: false });
      return { ok: false, error: `sshd reload failed: ${reload.stderr || reload.output}` };
    }
  }
  setJson('security_ssh', { port, password_authentication: !!body.password_authentication, permit_root_login: permit, max_auth_tries: max });
  audit(actor, 'admin', 'security.ssh.save', `port ${port}`, '');
  return { ok: true, simulated: config.provider !== 'linux', port };
}

export function listRootKeys() {
  return all('SELECT * FROM root_ssh_keys ORDER BY created_at DESC');
}

function fingerprint(pub) {
  const r = spawnSync('ssh-keygen', ['-lf', '/dev/stdin'], { input: pub + '\n', encoding: 'utf8' });
  return r.status === 0 ? r.stdout.trim().split(/\s+/)[1] || '' : '';
}

export function importRootKey(name, publicKey, actor = 'admin') {
  const pub = String(publicKey || '').trim();
  if (!/^(ssh-(rsa|ed25519)|ecdsa-sha2-nistp\d+)\s+[A-Za-z0-9+/=]+/.test(pub)) return { ok: false, error: 'Invalid SSH public key' };
  const label = String(name || '').trim().slice(0, 80) || 'imported';
  const marker = `openadmin:${label}:${Date.now()}`;
  const current = readManaged(ROOT_KEYS) || '';
  writeManaged(ROOT_KEYS, `${current}${current && !current.endsWith('\n') ? '\n' : ''}# ${marker}\n${pub}\n`, { mode: 0o600 });
  run('INSERT INTO root_ssh_keys(name, public_key, fingerprint, created_at) VALUES(?,?,?,?)', label, pub, fingerprint(pub), nowIso());
  audit(actor, 'admin', 'security.rootkey.import', label, '');
  return { ok: true, fingerprint: fingerprint(pub), simulated: config.provider !== 'linux' };
}

export function generateRootKey(name, actor = 'admin') {
  const label = String(name || '').trim().slice(0, 80) || 'generated';
  const safe = label.replace(/[^a-z0-9_-]/gi, '_');
  const dir = '/var/lib/openadmin/secure/root-keys';
  const keyPath = config.provider === 'linux' ? path.join(dir, `${safe}-${Date.now()}`) : managedPath(path.join(dir, `${safe}-${Date.now()}`));
  fs.mkdirSync(path.dirname(keyPath), { recursive: true, mode: 0o700 });
  const r = sh('ssh-keygen', ['-t', 'ed25519', '-N', '', '-C', `openadmin-${label}`, '-f', keyPath]);
  if (!r.ok) return { ok: false, error: r.stderr || r.error || 'ssh-keygen failed' };
  const pub = fs.readFileSync(`${keyPath}.pub`, 'utf8').trim();
  const marker = `openadmin:${label}:${Date.now()}`;
  const current = readManaged(ROOT_KEYS) || '';
  writeManaged(ROOT_KEYS, `${current}${current && !current.endsWith('\n') ? '\n' : ''}# ${marker}\n${pub}\n`, { mode: 0o600 });
  run('INSERT INTO root_ssh_keys(name, public_key, fingerprint, private_path, created_at) VALUES(?,?,?,?,?)', label, pub, fingerprint(pub), keyPath, nowIso());
  audit(actor, 'admin', 'security.rootkey.generate', label, '');
  return { ok: true, publicKey: pub, privateKey: fs.readFileSync(keyPath, 'utf8'), fingerprint: fingerprint(pub), simulated: config.provider !== 'linux' };
}

export function deleteRootKey(id, actor = 'admin') {
  const row = get('SELECT * FROM root_ssh_keys WHERE id = ?', Number(id));
  if (!row) return { ok: false, error: 'Not found' };
  const lines = (readManaged(ROOT_KEYS) || '').split('\n');
  const filtered = [];
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].startsWith('# openadmin:') && lines[i + 1] === row.public_key) { i++; continue; }
    filtered.push(lines[i]);
  }
  writeManaged(ROOT_KEYS, filtered.join('\n').replace(/\n+$/, '') + '\n', { mode: 0o600 });
  run('DELETE FROM root_ssh_keys WHERE id = ?', row.id);
  audit(actor, 'admin', 'security.rootkey.delete', row.name, '');
  return { ok: true };
}

export function getPasswordPolicy() {
  return getJson('security_password_policy', { minlen: 10, minclass: 3, maxrepeat: 3, enforce_root: true, dictcheck: false });
}

export function savePasswordPolicy(body, actor = 'admin') {
  const policy = {
    minlen: Math.min(64, Math.max(8, Number(body.minlen || 10))),
    minclass: Math.min(4, Math.max(1, Number(body.minclass || 3))),
    maxrepeat: Math.min(10, Math.max(1, Number(body.maxrepeat || 3))),
    enforce_root: !!body.enforce_root,
    dictcheck: !!body.dictcheck,
  };
  setJson('security_password_policy', policy);
  writeManaged(PWSQUALITY, `# Managed by OpenAdmin\nminlen = ${policy.minlen}\nminclass = ${policy.minclass}\nmaxrepeat = ${policy.maxrepeat}\n${policy.dictcheck ? 'dictcheck = 1\n' : ''}enforce_for_root = ${policy.enforce_root ? 1 : 0}\n`, { mode: 0o644 });
  audit(actor, 'admin', 'security.password_policy', `minlen=${policy.minlen}`, '');
  return { ok: true, policy };
}

export function passwordPolicyError(password, policy = getPasswordPolicy()) {
  const pw = String(password || '');
  if (pw.length < policy.minlen) return `Hasło musi mieć co najmniej ${policy.minlen} znaków`;
  const classes = [/[a-z]/, /[A-Z]/, /[0-9]/, /[^A-Za-z0-9]/].filter((re) => re.test(pw)).length;
  if (classes < policy.minclass) return `Hasło musi zawierać ${policy.minclass} rodzaje znaków (małe/duże/cyfry/znaki specjalne)`;
  return '';
}

export function countryStatus() {
  const rows = all('SELECT * FROM country_blocks ORDER BY country');
  const dir = path.join(config.dataDir, 'geoip');
  return { rows, cached: fs.existsSync(dir) ? fs.readdirSync(dir).length : 0 };
}

export async function setCountry(country, enabled, actor = 'admin') {
  const cc = String(country || '').toLowerCase();
  if (!/^[a-z]{2}$/.test(cc)) return { ok: false, error: 'Country code must be two letters' };
  if (enabled) run("INSERT OR IGNORE INTO country_blocks(country, mode, created_at) VALUES(?, 'block', ?)", cc, nowIso());
  else run('DELETE FROM country_blocks WHERE country = ?', cc);
  const refresh = enabled ? await downloadCountry(cc) : { ok: true };
  audit(actor, 'admin', 'security.country', `${cc}:${enabled ? 'block' : 'allow'}`, '');
  return { ok: true, cached: refresh.ok, error: refresh.ok ? '' : refresh.error };
}

async function downloadCountry(cc) {
  if (config.provider !== 'linux') {
    const dir = path.join(config.dataDir, 'geoip');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, `${cc}-aggregated.zone`), '192.0.2.0/24\n');
    return { ok: true, simulated: true };
  }
  if (!which('curl')) return { ok: false, error: 'curl is required to download country IP lists' };
  const dir = path.join(config.dataDir, 'geoip');
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  for (const [suffix, url] of [
    ['', `https://www.ipdeny.com/ipblocks/data/aggregated/${cc}-aggregated.zone`],
    ['.ipv6', `https://www.ipdeny.com/ipv6/ipaddresses/aggregated/${cc}-aggregated.zone`],
  ]) {
    const out = path.join(dir, `${cc}-aggregated.zone${suffix}`);
    const r = sh('curl', ['-fsSL', '--max-time', '30', '-o', out, url], { timeout: 40000 });
    if (!r.ok && suffix === '') return { ok: false, error: `Could not download ${cc} list: ${r.stderr || r.error}` };
  }
  return { ok: true };
}

export function compilerState() {
  const users = all("SELECT username FROM users WHERE level IN ('user','reseller') ORDER BY username");
  const compiler = sh('getent', ['group', 'compiler']);
  const wheel = sh('getent', ['group', 'sudo']).ok ? sh('getent', ['group', 'sudo']) : sh('getent', ['group', 'wheel']);
  const members = (line) => line.split(':')[3] ? line.split(':')[3].split(',').filter(Boolean) : [];
  return {
    enabled: setting('compiler_restricted', '0') === '1',
    compilerMembers: members(compiler.stdout),
    wheelMembers: members(wheel.stdout),
    users: users.map((u) => u.username),
    gcc: which('gcc'),
  };
}

export function setGroupAccess(group, user, enabled, actor = 'admin') {
  if (!['compiler', 'sudo', 'wheel'].includes(group)) return { ok: false, error: 'Unsupported group' };
  if (!/^[a-z_][a-z0-9_-]{0,31}$/i.test(String(user))) return { ok: false, error: 'Invalid user' };
  if (config.provider !== 'linux') return { ok: true, simulated: true, output: `${user} ${enabled ? 'added to' : 'removed from'} ${group} in sandbox` };
  if (!isRoot()) return { ok: false, error: 'Root privileges required' };
  if (group === 'compiler' && !sh('getent', ['group', 'compiler']).ok) sh('groupadd', ['compiler']);
  const r = enabled ? sh('usermod', ['-aG', group, user]) : sh('gpasswd', ['-d', user, group]);
  if (!r.ok) return { ok: false, error: r.stderr || r.error };
  audit(actor, 'admin', `security.group.${enabled ? 'add' : 'remove'}`, `${group}:${user}`, '');
  return { ok: true, output: r.stdout || `${group} updated` };
}

export function setCompilerRestriction(enabled, actor = 'admin') {
  setSetting('compiler_restricted', enabled ? '1' : '0');
  if (config.provider !== 'linux') return { ok: true, simulated: true };
  if (!isRoot()) return { ok: false, error: 'Root privileges required' };
  for (const bin of ['/usr/bin/gcc', '/usr/bin/g++', '/usr/bin/cc']) {
    if (!fs.existsSync(bin)) continue;
    const mode = enabled ? 0o750 : 0o755;
    try { fs.chmodSync(bin, mode); } catch { /* ignore */ }
  }
  audit(actor, 'admin', 'security.compiler', enabled ? 'restricted' : 'open', '');
  return { ok: true, simulated: false };
}

export function getForkBomb() {
  return getJson('security_forkbomb', { enabled: false, nproc: 200, nofile: 4096 });
}

export function saveForkBomb(body, actor = 'admin') {
  const cfg = {
    enabled: !!body.enabled,
    nproc: Math.min(100000, Math.max(16, Number(body.nproc || 200))),
    nofile: Math.min(1048576, Math.max(256, Number(body.nofile || 4096))),
  };
  setJson('security_forkbomb', cfg);
  writeManaged(LIMITS, cfg.enabled ? `# Managed by OpenAdmin\n* hard nproc ${cfg.nproc}\n* hard nofile ${cfg.nofile}\n` : '# OpenAdmin: fork-bomb limits disabled\n', { mode: 0o644 });
  audit(actor, 'admin', 'security.forkbomb', cfg.enabled ? 'on' : 'off', '');
  return { ok: true, cfg };
}

export function smtpRestrictions() {
  return setting('smtp_restrictions', '0') === '1';
}

export function saveSmtpRestrictions(enabled, actor = 'admin') {
  setSetting('smtp_restrictions', enabled ? '1' : '0');
  const applied = applyFirewall();
  audit(actor, 'admin', 'security.smtp_restrictions', enabled ? 'on' : 'off', '');
  return { ok: applied.ok, applied, error: applied.error || '' };
}

export function modsecStatus() {
  const caps = capabilities();
  const conf = readManaged(MODSEC_CONF) || '';
  return {
    supported: caps.modsecurity,
    apache: caps.apache,
    conf: MODSEC_CONF,
    engine: /SecRuleEngine\s+(\w+)/.exec(conf)?.[1] || 'Off',
    paranoia: /SecAction.*paranoia_level[^0-9]*(\d)/.exec(conf)?.[1] || '2',
    crs: fs.existsSync('/usr/share/modsecurity-crs'),
  };
}

export function saveModsec(body, actor = 'admin') {
  const engine = ['On', 'Off', 'DetectionOnly'].includes(String(body.engine)) ? String(body.engine) : 'On';
  const paranoia = Math.min(4, Math.max(1, Number(body.paranoia || 2)));
  const text = `# Managed by OpenAdmin\nSecRuleEngine ${engine}\nSecAction "id:900000,phase:1,pass,t:none,nolog,setvar:tx.paranoia_level=${paranoia}"\n`;
  writeManaged(MODSEC_CONF, text, { mode: 0o600 });
  if (config.provider === 'linux' && isRoot() && capabilities().apache) {
    const r = sh('apache2ctl', ['configtest']);
    if (!r.ok) return { ok: false, error: `Apache validation failed: ${r.stderr || r.error}` };
    serviceReload('apache2');
  }
  audit(actor, 'admin', 'security.modsec.save', `${engine}/PL${paranoia}`, '');
  return { ok: true, simulated: config.provider !== 'linux' || !capabilities().modsecurity };
}

export function securitySummary() {
  const caps = capabilities();
  const blocks = blockRows();
  const ssh = getSsh();
  const fork = getForkBomb();
  const smtp = smtpRestrictions();
  const mod = modsecStatus();
  const keys = listRootKeys();
  const posture = [
    { key: 'firewall', priority: 'P0', label: 'Firewall nftables', ok: !!caps.nft, evidence: caps.nft ? 'nft dostępny' : 'brak nftables', impact: 'Brak filtrowania ruchu na hoście', action: '?tab=firewall', fix: 'Zainstaluj nftables i wdróż reguły' },
    { key: 'ssh-password', priority: 'P0', label: 'Logowanie SSH hasłem', ok: !ssh.password_authentication, evidence: ssh.password_authentication ? 'PasswordAuthentication yes' : 'wyłączone', impact: 'Zwiększone ryzyko brute force SSH', action: '?tab=ssh', fix: 'Wyłącz hasła, używaj kluczy' },
    { key: 'root-keys', priority: 'P1', label: 'Klucze roota', ok: keys.length > 0, evidence: `${keys.length} klucz(y)`, impact: 'Brak awaryjnego dostępu po kluczu', action: '?tab=keys', fix: 'Dodaj klucz publiczny roota' },
    { key: 'forkbomb', priority: 'P1', label: 'Ochrona fork bomb', ok: !!fork.enabled, evidence: fork.enabled ? `nproc=${fork.nproc}` : 'wyłączona', impact: 'Jeden proces może wyczerpać PID-y', action: '?tab=groups', fix: 'Włącz limity nproc/nofile' },
    { key: 'smtp-restrictions', priority: 'P1', label: 'Ograniczenia SMTP', ok: !!smtp.enabled, evidence: smtp.enabled ? 'aktywne' : 'wyłączone', impact: 'Możliwy spam wychodzący z kont', action: '?tab=mail', fix: 'Włącz ograniczenia egress' },
    { key: 'modsecurity', priority: 'P2', label: 'ModSecurity / WAF', ok: !!mod.supported, evidence: mod.supported ? mod.engine : 'niedostępny', impact: 'Brak reguł WAF dla aplikacji WWW', action: '?tab=waf', fix: 'Zainstaluj mod_security2 lub WAF nginx' },
  ];
  const passed = posture.filter((x) => x.ok).length;
  return {
    caps, blocks: blocks.length, countries: all('SELECT * FROM country_blocks').length,
    password: getPasswordPolicy(), forkbomb: fork, ssh, smtp, modsec: mod,
    posture, score: Math.round((passed / posture.length) * 100), passed, total: posture.length,
  };
}
